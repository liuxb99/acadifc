/// True when WHATWG Big5 would encode `ch` to bytes that classic CP950 decodes
/// differently (so AutoCAD-written text uses a `\U+XXXX` escape instead).
pub(crate) fn prefers_escape(encoding: &'static Encoding, ch: char) -> bool {
    encoding == encoding_rs::BIG5
        && CP950_DIFF
            .binary_search_by_key(&(ch as u32), |(c, _)| *c)
            .is_ok()
}
